-- ==========================================================================
-- Geographic sweep discovery: search areas, sweep tracking
-- ==========================================================================

-- 1. Search areas reference + tracking table
-- Each row is a postcode district that can be swept for a given vertical
CREATE TABLE IF NOT EXISTS business_intel.search_areas (
                                                           id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    area_code       TEXT NOT NULL,          -- e.g. 'BT' (postcode area)
    district_code   TEXT NOT NULL,          -- e.g. 'BT4' (postcode district)
    area_name       TEXT,                   -- e.g. 'Belfast'
    country         TEXT DEFAULT 'GB',

    -- Sweep tracking per vertical
    -- For now veterinary only; we can add a vertical_id FK later if needed
    last_swept_at   TIMESTAMPTZ,
    sweep_count     INT DEFAULT 0,
    last_result_count INT,                  -- how many results came back last time
    candidates_found INT DEFAULT 0,         -- cumulative new candidates from this area

    created_at      TIMESTAMPTZ DEFAULT NOW()
    );

CREATE UNIQUE INDEX IF NOT EXISTS idx_sa_district_country
    ON business_intel.search_areas(district_code, country);
CREATE INDEX IF NOT EXISTS idx_sa_not_swept
    ON business_intel.search_areas(last_swept_at) WHERE last_swept_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_sa_area_code
    ON business_intel.search_areas(area_code);

